// Icon Button component
interface IconButtonProps {
  icon: string
  size?: 'xs' | 'sm' | 'md' | 'lg' | 'xl' | '2xl' | '3xl'
  color?: string
  variant?: 'primary' | 'secondary' | 'success' | 'warning' | 'error' | 'info' | 'ghost' | 'outline'
  disabled?: boolean
  className?: string
  style?: React.CSSProperties
  onClick?: () => void
  onMouseEnter?: () => void
  onMouseLeave?: () => void
}

export const IconButton: React.FC<IconButtonProps> = ({
  icon,
  size = 'md',
  color,
  variant = 'ghost',
  disabled = false,
  className = '',
  style = {},
  onClick,
  onMouseEnter,
  onMouseLeave
}) => {
  const getVariantClass = () => {
    switch (variant) {
      case 'primary':
        return 'bg-blue-500 text-white hover:bg-blue-600'
      case 'secondary':
        return 'bg-gray-500 text-white hover:bg-gray-600'
      case 'success':
        return 'bg-green-500 text-white hover:bg-green-600'
      case 'warning':
        return 'bg-yellow-500 text-white hover:bg-yellow-600'
      case 'error':
        return 'bg-red-500 text-white hover:bg-red-600'
      case 'info':
        return 'bg-blue-500 text-white hover:bg-blue-600'
      case 'ghost':
        return 'bg-transparent text-gray-500 hover:bg-gray-100 hover:text-gray-700'
      case 'outline':
        return 'border border-gray-300 text-gray-700 hover:bg-gray-50'
      default:
        return 'bg-transparent text-gray-500 hover:bg-gray-100 hover:text-gray-700'
    }
  }

  const getSizeClass = () => {
    switch (size) {
      case 'xs':
        return 'p-1'
      case 'sm':
        return 'p-1.5'
      case 'md':
        return 'p-2'
      case 'lg':
        return 'p-2.5'
      case 'xl':
        return 'p-3'
      case '2xl':
        return 'p-4'
      case '3xl':
        return 'p-5'
      default:
        return 'p-2'
    }
  }

  const buttonClasses = [
    'inline-flex items-center justify-center rounded-md transition-colors duration-200',
    getVariantClass(),
    getSizeClass(),
    disabled ? 'opacity-50 cursor-not-allowed' : 'cursor-pointer',
    className
  ].filter(Boolean).join(' ')

  return (
    <button
      className={buttonClasses}
      style={style}
      disabled={disabled}
      onClick={onClick}
      onMouseEnter={onMouseEnter}
      onMouseLeave={onMouseLeave}
    >
      <Icon name={icon} size={size} color={color} />
    </button>
  )
}
